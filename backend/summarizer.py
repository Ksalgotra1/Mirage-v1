def deterministic_summary(findings: dict[str, Any]) -> str:
    """
    Structured deterministic summary using forensic signals directly.
    Formatted with section headers (▸) and bullets (•) to match the UI dossier parser.
    Used as fallback when GEMINI_API_KEY is not configured or offline.
    """
    fused = findings.get("fused") or {}
    verdict = str(fused.get("verdict", "UNKNOWN")).upper()
    score = fused.get("score", 0.0)
    forensic_band = fused.get("forensic_band", "clean")
    forensics = findings.get("steganography_forensics")
    explanation = fused.get("explanation", "")

    if verdict == "BENIGN":
        lines = [
            "▸ OBSERVATION",
            f"• Verdict: BENIGN with fused risk score of {score:.4f}.",
            "• All applicable inspection layers reported no confirmed security threats.",
            "• Static analysis found normal model architecture and expected weight distributions.",
            "",
            "▸ NEXT STEPS",
            "• No immediate security action required; model is cleared for standard staging.",
            "• Monitor artifact behavior; static analysis cannot guarantee absence of runtime threats.",
            "",
            "Note: Deterministic analysis generated by MIRAGE 4-layer engine (offline fallback).",
        ]
        return "\n".join(lines)

    if verdict == "SUSPICIOUS" or forensic_band == "suspicious":
        lines = [
            "▸ OBSERVATION",
            f"• Verdict: SUSPICIOUS with fused risk score of {score:.4f}.",
        ]
        if explanation:
            lines.append(f"• {explanation}")
        else:
            lines.append("• Elevated anomaly signals detected across inspection layers.")

        if forensics and forensic_band in ("suspicious", "malicious"):
            bd = forensics.get("bit_depth") or {}
            ent = forensics.get("entropy") or {}
            dist = forensics.get("distribution") or {}
            if bd.get("estimated_x", 0) > 0:
                lines.append(
                    f"• Detected {bd['estimated_x']}-bit LSB embedding rate ({bd.get('stealth_assessment', 'Uncalibrated')})."
                )
            if ent.get("bits_per_byte") is not None:
                lines.append(
                    f"• Payload entropy: {ent.get('bits_per_byte', 0):.3f} bits/byte ({ent.get('classification', 'unknown')})."
                )
            if dist.get("pattern") and dist.get("pattern") != "unknown":
                lines.append(
                    f"• Distribution geometry: {dist.get('pattern')} pattern (sophistication: {dist.get('sophistication', 'moderate')})."
                )

        lines.extend([
            "",
            "▸ POSSIBLE ATTACKER INTENT",
            "• Potential covert channel or preliminary steganographic payload embedding.",
            "• Attacker objective remains inconclusive; may represent evasion testing or quantization artifacts.",
            "",
            "▸ NEXT STEPS",
            "• Conduct secondary manual inspection of flagged weight tensors.",
            "• Quarantine artifact pending review by security personnel before deployment.",
            "• MIRAGE Disarm module is available if artifact is confirmed malicious.",
            "",
            "Note: Deterministic analysis generated by MIRAGE 4-layer engine (offline fallback).",
        ])
        return "\n".join(lines)

    # Malicious verdict (or high risk default)
    lines = [
        "▸ OBSERVATION",
        f"• Verdict: MALICIOUS with fused risk score of {score:.4f}.",
    ]
    if explanation:
        lines.append(f"• {explanation}")

    if forensics and forensic_band in ("suspicious", "malicious"):
        bd = forensics.get("bit_depth") or {}
        ent = forensics.get("entropy") or {}
        cap = forensics.get("capacity") or {}
        dist = forensics.get("distribution") or {}
        magic = forensics.get("magic_bytes") or {}

        if bd.get("estimated_x", 0) > 0:
            lines.append(
                f"• Forensic analysis detected {bd['estimated_x']}-bit LSB embedding "
                f"({bd.get('stealth_assessment', '')})."
            )
        if ent.get("bits_per_byte") is not None:
            lines.append(
                f"• Payload entropy: {ent.get('bits_per_byte', 0):.3f} bits/byte "
                f"({ent.get('classification', 'unknown')})."
            )
        if cap and (cap.get("human_readable") or cap.get("estimated_bytes", 0) > 0):
            hr = cap.get("human_readable", f"{cap.get('estimated_bytes', 0)} bytes")
            lines.append(
                f"• Estimated payload capacity: {hr} ({cap.get('classification', '')})."
            )
        if dist and dist.get("sophistication"):
            lines.append(
                f"• Distribution pattern: {dist.get('pattern', 'unknown')} — "
                f"sophistication level: {dist['sophistication']}."
            )
        if magic and magic.get("detected"):
            lines.append(
                f"• Magic byte signature identified: {magic.get('signature')} ({magic.get('description', '')})."
            )

    # Attacker Intent
    lines.extend([
        "",
        "▸ POSSIBLE ATTACKER INTENT",
    ])
    intent_added = False
    if forensics:
        ent_cls = (forensics.get("entropy") or {}).get("classification", "")
        cap_cls = (forensics.get("capacity") or {}).get("classification", "")
        if "Encrypted" in ent_cls:
            lines.append("• Exfiltration or C2 delivery via encrypted binary payload hidden in model weights.")
            intent_added = True
        elif "RAT" in cap_cls or "Executable" in cap_cls:
            lines.append("• Full binary dropper or remote access trojan (RAT) staged for post-deployment execution.")
            intent_added = True

    if not intent_added:
        lines.append("• Covert steganographic payload delivery bypassing perimeter file scanners.")
    lines.append("• Target compromise or supply-chain poisoning upon deserialization or deployment.")

    # Next steps
    lines.extend([
        "",
        "▸ NEXT STEPS",
        "• Quarantine this artifact immediately — do not deploy or execute.",
        "• Use the built-in Disarm module for one-click remediation and clean model download.",
        "• Review contributing layer evidence before releasing any modified artifact.",
        "",
        "Note: Deterministic analysis generated by MIRAGE 4-layer engine (offline fallback).",
    ])

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Gemini LLM call
# ---------------------------------------------------------------------------

def gemini_summary(findings: dict[str, Any]) -> str | None:
    """Ask Gemini to explain structured findings when GEMINI_API_KEY is configured."""
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        return None

    # Token budget driven by effective band (respects fused verdict)
    effective_band = _effective_band(findings)
    max_tokens = 1200 if effective_band == "malicious" else (800 if effective_band == "suspicious" else 400)

    try:
        from google import genai
        from google.genai import types

        client = genai.Client(api_key=api_key)
        response = client.models.generate_content(
            model=os.getenv("GEMINI_MODEL", "gemini-3.5-flash-lite"),
            contents=build_llm_prompt(findings),
            config=types.GenerateContentConfig(
                temperature=0.2,
                max_output_tokens=max_tokens,
            ),
        )
        text = getattr(response, "text", None)
        return text.strip() if text else None
    except Exception:
        # A provider outage must never break scanning or alter the detector verdict.
        return None


# ---------------------------------------------------------------------------
# Public interface
# ---------------------------------------------------------------------------

def summarize_findings(findings: dict[str, Any], llm_text: str | None = None) -> dict[str, Any]:
    """Return an explanation plus provenance while preserving the detector result."""
    generated_text = llm_text or gemini_summary(findings)
    return {
        "summary": (
            generated_text.strip()
            if generated_text and generated_text.strip()
            else deterministic_summary(findings)
        ),
        "provider": (
            "configured_llm" if llm_text
            else ("gemini_api" if generated_text else "deterministic_fallback")
        ),
        "verdict_source": "fusion_engine",
        "forensic_band": (findings.get("fused") or {}).get("forensic_band", "clean"),
        "prompt": build_llm_prompt(findings),
    }
